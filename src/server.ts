// Импортируем функцию сборки Fastify-приложения из соседнего файла app.ts.
// Расширение .js указывается даже для TypeScript-файла — это требование ESM
// при moduleResolution: "Bundler"/"NodeNext". TS сам подставит .ts при сборке.
import { buildApp } from './app.js';

// Импортируем типизированный объект с переменными окружения (PORT, HOST и т.д.).
// Он читает .env, проверяет обязательные переменные и отдаёт их как обычный объект.
import { env } from './config/env.js';

// Главная функция запуска сервера. async нужен, потому что listen() возвращает Promise.
async function main() {
  // Собираем приложение: создаётся Fastify, подключаются плагины и маршруты.
  // await обязателен — buildApp() асинхронная (регистрация плагинов асинхронна).
  const app = await buildApp();

  // try/catch — чтобы поймать ошибки запуска (порт занят, нет прав, ошибка плагина).
  try {
    // Запускаем HTTP-сервер на хосте и порту из .env.
    // host — например 127.0.0.1, port — например 3000.
    await app.listen({ host: env.host, port: env.port });

    // Пишем в лог сообщение, что сервер запустился.
    // app.log — логгер Fastify, в dev он настроен на pino-pretty.
    app.log.info(`Server started: http://${env.host}:${env.port}`);
  } catch (err) {
    // Если запуск упал — логируем ошибку целиком (со стеком).
    app.log.error(err);

    // Завершаем процесс с кодом 1 — это сигнал «упало с ошибкой».
    // Без этого Node мог бы остаться висеть, ничего не делая.
    process.exit(1);
  }
}

// Вызываем main(). Функция сама ловит ошибки внутри, поэтому .catch() здесь не нужен.
main();